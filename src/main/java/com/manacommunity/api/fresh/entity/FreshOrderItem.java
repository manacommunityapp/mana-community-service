package com.manacommunity.api.fresh.entity;

import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;
import java.time.OffsetDateTime;

/**
 * One line of a {@link FreshOrder}.
 *
 * <p>The table has existed since V498; only the Java mapping was missing, so orders
 * were persisted with a computed total and no record of what was actually ordered.
 *
 * <p>{@code unit_price} is captured at order time rather than read from the product
 * later — a catalogue price change must not retroactively alter what someone was
 * charged. {@code subtotal} is a generated column in Postgres, so it is mapped
 * read-only and never written from here.
 */
@Entity
@Table(name = "fresh_order_item", indexes = {
    @Index(name = "idx_foi_order",   columnList = "order_id"),
    @Index(name = "idx_foi_product", columnList = "product_id")
})
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class FreshOrderItem {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Back-reference; ignored in JSON so serialising an order does not recurse. */
    @JsonIgnore
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "order_id", nullable = false)
    private FreshOrder order;

    @Column(name = "product_id", nullable = false)
    private Long productId;

    @Column(nullable = false)
    private Integer quantity;

    @Column(name = "unit_price", nullable = false, precision = 10, scale = 2)
    private BigDecimal unitPrice;

    /** Generated by Postgres as quantity * unit_price. Never written from Java. */
    @Column(name = "subtotal", precision = 12, scale = 2, insertable = false, updatable = false)
    private BigDecimal subtotal;

    @Column(name = "created_at", nullable = false, updatable = false)
    private OffsetDateTime createdAt;

    @PrePersist
    void onCreate() {
        if (createdAt == null) createdAt = OffsetDateTime.now();
    }
}
