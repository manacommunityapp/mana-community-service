    @Transactional
    public void withdrawAndReplaceMember(Long cycleId, AppUser adminUser, ReplaceMemberRequest request) {
        KittyPartyCycle cycle = cycleRepository.findById(cycleId)
                .orElseThrow(() -> new IllegalArgumentException("Cycle not found"));

        authorizationService.assertAdminOrOwner(cycle.getCircle().getId(), adminUser.getId());

        AppUser oldUser = userRepository.findById(request.getOldUserId())
                .orElseThrow(() -> new IllegalArgumentException("Old user not found"));
        AppUser newUser = userRepository.findById(request.getNewUserId())
                .orElseThrow(() -> new IllegalArgumentException("Replacement user not found"));

        int currentPeriod = computeCurrentPeriod(cycle);

        // 1. Ensure new user is an active member of circle
        KittyPartyMember newMember = memberRepository.findByCircleIdAndUserId(cycle.getCircle().getId(), newUser.getId())
                .orElseGet(() -> KittyPartyMember.builder()
                        .circle(cycle.getCircle())
                        .user(newUser)
                        .community(newUser.getCommunity())
                        .roleCode("MEMBER")
                        .build());
        newMember.setMembershipStatus("ACTIVE");
        newMember.setApprovedBy(adminUser);
        newMember.setApprovedAt(LocalDateTime.now());
        memberRepository.save(newMember);

        // 2. Mark old member as LEFT in circle
        memberRepository.findByCircleIdAndUserId(cycle.getCircle().getId(), oldUser.getId())
                .ifPresent(m -> {
                    m.setMembershipStatus("LEFT");
                    memberRepository.save(m);
                });

        // 3. Reassign future un-disbursed rotations
        List<KittyPartyRotation> rotations = rotationRepository.findByCycleIdOrderByPeriodNumberAsc(cycleId);
        for (KittyPartyRotation r : rotations) {
            if (r.getBeneficiaryUser().getId().equals(oldUser.getId()) && !"DISBURSED".equalsIgnoreCase(r.getRotationStatus())) {
                r.setBeneficiaryUser(newUser);
                r.setRotationStatus("SWAPPED");
                rotationRepository.save(r);
            }
        }

        // 4. Feature 8: Record Member Replacement in Audit Log
        recordAuditLog(
                cycle,
                cycle.getCircle(),
                "MEMBER_REPLACED",
                adminUser,
                "Member " + oldUser.getFullName() + " replaced by " + newUser.getFullName() + ". Reason: " + request.getReason(),
                "{\"oldUserId\":" + oldUser.getId() + ",\"newUserId\":" + newUser.getId() + ",\"reason\":\"" + request.getReason() + "\"}"
        );

        log.info("Replaced member {} with {} in cycle {}", oldUser.getId(), newUser.getId(), cycleId);
    }

