    @Transactional(readOnly = true)
    public MonthlyStatementResponse generateMonthlyStatement(Long cycleId, Integer periodNumber) {
        KittyPartyCycle cycle = cycleRepository.findById(cycleId)
                .orElseThrow(() -> new IllegalArgumentException("Cycle not found"));

        int targetPeriod = (periodNumber != null) ? periodNumber : computeCurrentPeriod(cycle);
        LocalDate periodStartDate = cycle.getStartDate().plusMonths(targetPeriod - 1);
        LocalDate periodDueDate = computePeriodDueDate(cycle.getStartDate(), targetPeriod);

        KittyPartyRotation rotation = rotationRepository.findByCycleIdAndPeriodNumber(cycleId, targetPeriod).orElse(null);

        List<KittyPartyContribution> contributions = contributionRepository.findByCycleIdAndPeriodNumber(cycleId, targetPeriod);
        BigDecimal totalExpected = cycle.getContributionAmount().multiply(BigDecimal.valueOf(cycle.getMemberCount()));
        BigDecimal totalCollected = BigDecimal.ZERO;

        LocalDate today = LocalDate.now();
        List<StatementLineItemDto> lineItems = new ArrayList<>();

        for (KittyPartyContribution c : contributions) {
            boolean isPaid = "PAID".equalsIgnoreCase(c.getPaymentStatus()) || "VERIFIED".equalsIgnoreCase(c.getPaymentStatus());
            if (isPaid && c.getRecordedAmount() != null) {
                totalCollected = totalCollected.add(c.getRecordedAmount());
            }
            boolean isPending = !isPaid;
            boolean isOverdue = isPending && today.isAfter(periodDueDate);
            long daysOverdue = isOverdue ? ChronoUnit.DAYS.between(periodDueDate, today) : 0L;

            lineItems.add(StatementLineItemDto.builder()
                    .memberUserId(c.getMemberUser().getId())
                    .memberName(c.getMemberUser().getFullName())
                    .expectedAmount(c.getExpectedAmount())
                    .recordedAmount(c.getRecordedAmount())
                    .paymentStatus(c.getPaymentStatus())
                    .externalRef(c.getExternalRef())
                    .receiptUrl(c.getReceiptUrl())
                    .notes(c.getNotes())
                    .verifiedByName(c.getVerifiedBy() != null ? c.getVerifiedBy().getFullName() : null)
                    .verifiedAt(c.getVerifiedAt())
                    .isOverdue(isOverdue)
                    .daysOverdue(daysOverdue)
                    .build());
        }

        BigDecimal totalPending = totalExpected.subtract(totalCollected).max(BigDecimal.ZERO);

        return MonthlyStatementResponse.builder()
                .cycleId(cycle.getId())
                .circleId(cycle.getCircle().getId())
                .circleName(cycle.getCircle().getCircleName())
                .cycleName(cycle.getCycleName())
                .periodNumber(targetPeriod)
                .periodStartDate(periodStartDate)
                .periodDueDate(periodDueDate)
                .contributionAmount(cycle.getContributionAmount())
                .totalExpected(totalExpected)
                .totalCollected(totalCollected)
                .totalPending(totalPending)
                .beneficiaryUserId(rotation != null ? rotation.getBeneficiaryUser().getId() : null)
                .beneficiaryName(rotation != null ? rotation.getBeneficiaryUser().getFullName() : "Unassigned")
                .beneficiaryUpiId(rotation != null && rotation.getBeneficiaryUser().getPhone() != null
                        ? rotation.getBeneficiaryUser().getPhone().replaceAll("[^0-9]", "") + "@upi" : null)
                .payoutStatus(rotation != null ? rotation.getRotationStatus() : "PLANNED")
                .externalPayoutRef(rotation != null ? rotation.getExternalPayoutRef() : null)
                .payoutDisbursedAt(rotation != null ? rotation.getDisbursedAt() : null)
                .lineItems(lineItems)
                .legalDisclaimer(LEGAL_DISCLAIMER)
                .build();
    }

