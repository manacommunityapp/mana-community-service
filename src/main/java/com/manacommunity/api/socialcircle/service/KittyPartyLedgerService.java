    @Transactional
    public DisputeResponse createDispute(Long circleId, AppUser user, CreateDisputeRequest request) {
        KittyPartyCircle circle = circleRepository.findByIdAndDeletedAtIsNull(circleId)
                .orElseThrow(() -> new IllegalArgumentException("Circle not found"));

        KittyPartyCycle cycle = null;
        if (request.getCycleId() != null) {
            cycle = cycleRepository.findById(request.getCycleId()).orElse(null);
        }

        KittyPartyDispute dispute = KittyPartyDispute.builder()
                .circle(circle)
                .cycle(cycle)
                .raisedBy(user)
                .disputeType(request.getDisputeType())
                .title(request.getTitle())
                .description(request.getDescription())
                .status("OPEN")
                .build();

        KittyPartyDispute saved = disputeRepository.save(dispute);

        if (cycle != null) {
            recordAuditLog(
                    cycle,
                    circle,
                    "DISPUTE_RAISED",
                    user,
                    "Dispute raised by " + user.getFullName() + ": " + request.getTitle(),
                    "{\"disputeId\":" + saved.getId() + ",\"type\":\"" + request.getDisputeType() + "\"}"
            );
        }

        return mapDisputeToResponse(saved);
    }

    @Transactional(readOnly = true)
    public List<DisputeResponse> getDisputes(Long circleId) {
        return disputeRepository.findByCircleIdOrderByCreatedAtDesc(circleId).stream()
                .map(this::mapDisputeToResponse)
                .collect(Collectors.toList());
    }

    @Transactional
    public DisputeResponse resolveDispute(Long circleId, Long disputeId, AppUser adminUser, ResolveDisputeRequest request) {
        authorizationService.assertAdminOrOwner(circleId, adminUser.getId());

        KittyPartyDispute dispute = disputeRepository.findById(disputeId)
                .orElseThrow(() -> new IllegalArgumentException("Dispute not found"));

        dispute.setStatus(request.getStatus());
        dispute.setResolutionNotes(request.getResolutionNotes());
        dispute.setResolvedBy(adminUser);
        dispute.setResolvedAt(LocalDateTime.now());
        dispute.setUpdatedAt(LocalDateTime.now());

        KittyPartyDispute saved = disputeRepository.save(dispute);

        if (dispute.getCycle() != null) {
            recordAuditLog(
                    dispute.getCycle(),
                    dispute.getCircle(),
                    "DISPUTE_RESOLVED",
                    adminUser,
                    "Dispute #" + disputeId + " marked as " + request.getStatus() + ". Notes: " + request.getResolutionNotes(),
                    "{\"disputeId\":" + disputeId + ",\"status\":\"" + request.getStatus() + "\"}"
            );
        }

        return mapDisputeToResponse(saved);
    }

    private DisputeResponse mapDisputeToResponse(KittyPartyDispute d) {
        return DisputeResponse.builder()
                .id(d.getId())
                .circleId(d.getCircle().getId())
                .cycleId(d.getCycle() != null ? d.getCycle().getId() : null)
                .raisedById(d.getRaisedBy().getId())
                .raisedByName(d.getRaisedBy().getFullName())
                .disputeType(d.getDisputeType())
                .title(d.getTitle())
                .description(d.getDescription())
                .status(d.getStatus())
                .resolutionNotes(d.getResolutionNotes())
                .resolvedById(d.getResolvedBy() != null ? d.getResolvedBy().getId() : null)
                .resolvedByName(d.getResolvedBy() != null ? d.getResolvedBy().getFullName() : null)
                .resolvedAt(d.getResolvedAt())
                .createdAt(d.getCreatedAt())
                .updatedAt(d.getUpdatedAt())
                .build();
    }

