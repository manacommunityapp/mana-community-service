    @Transactional
    public CycleSummaryResponse createCycle(Long circleId, AppUser creator, CreateCycleRequest request) {
        authorizationService.assertAdminOrOwner(circleId, creator.getId());

        KittyPartyCircle circle = circleRepository.findByIdAndDeletedAtIsNull(circleId)
                .orElseThrow(() -> new IllegalArgumentException("Circle not found"));

        LocalDate endDate = request.getStartDate().plusMonths(request.getMemberCount());

        KittyPartyCycle cycle = KittyPartyCycle.builder()
                .circle(circle)
                .cycleName(request.getCycleName().trim())
                .contributionAmount(request.getContributionAmount())
                .frequency(request.getFrequency() != null ? request.getFrequency() : "MONTHLY")
                .memberCount(request.getMemberCount())
                .startDate(request.getStartDate())
                .endDate(endDate)
                .financialMode("RECORD_ONLY") // Chit Funds Act 1982 compliance
                .legalConsentVer("2026_V1")
                .status("ACTIVE")
                .createdBy(creator)
                .build();

        KittyPartyCycle saved = cycleRepository.save(cycle);

        // Feature 1: Fixed rotation order sequencing
        List<Long> rotationUserIds = request.getBeneficiaryRotationUserIds();
        if (rotationUserIds == null || rotationUserIds.isEmpty()) {
            List<KittyPartyMember> activeMembers = memberRepository.findByCircleIdAndMembershipStatus(circleId, "ACTIVE");
            rotationUserIds = new ArrayList<>();
            rotationUserIds.add(creator.getId());
            for (KittyPartyMember m : activeMembers) {
                if (!m.getUser().getId().equals(creator.getId()) && rotationUserIds.size() < saved.getMemberCount()) {
                    rotationUserIds.add(m.getUser().getId());
                }
            }
        }

        int period = 1;
        for (Long beneficiaryId : rotationUserIds) {
            if (period > saved.getMemberCount()) break;
            AppUser beneficiary = userRepository.findById(beneficiaryId).orElse(null);
            if (beneficiary != null) {
                KittyPartyRotation rotation = KittyPartyRotation.builder()
                        .cycle(saved)
                        .beneficiaryUser(beneficiary)
                        .periodNumber(period)
                        .rotationStatus("PLANNED")
                        .build();
                rotationRepository.save(rotation);
                period++;
            }
        }

        // Feature 8: Record Cycle Creation in Audit Log
        recordAuditLog(
                saved,
                circle,
                "CYCLE_CREATED",
                creator,
                "Kitty savings cycle '" + saved.getCycleName() + "' created with contribution ₹" + saved.getContributionAmount(),
                "{\"memberCount\":" + saved.getMemberCount() + ",\"contributionAmount\":" + saved.getContributionAmount() + "}"
        );

        log.info("Created KittyPartyCycle id={} circleId={} amount={}", saved.getId(), circleId, saved.getContributionAmount());
        return getCycleSummary(saved.getId());
    }

