    @Transactional
    public SendRemindersResponse sendPaymentReminders(Long cycleId, AppUser adminUser, Integer periodNumber) {
        KittyPartyCycle cycle = cycleRepository.findById(cycleId)
                .orElseThrow(() -> new IllegalArgumentException("Cycle not found"));

        authorizationService.assertFinanceRole(cycle.getCircle().getId(), adminUser.getId());

        int targetPeriod = (periodNumber != null) ? periodNumber : computeCurrentPeriod(cycle);

        List<KittyPartyMember> activeMembers = memberRepository.findByCircleIdAndMembershipStatus(cycle.getCircle().getId(), "ACTIVE");
        List<KittyPartyContribution> contributions = contributionRepository.findByCycleIdAndPeriodNumber(cycleId, targetPeriod);

        Set<Long> paidUserIds = contributions.stream()
                .filter(c -> "PAID".equalsIgnoreCase(c.getPaymentStatus()) || "VERIFIED".equalsIgnoreCase(c.getPaymentStatus()))
                .map(c -> c.getMemberUser().getId())
                .collect(Collectors.toSet());

        List<String> remindedMembers = new ArrayList<>();

        for (KittyPartyMember member : activeMembers) {
            if (!paidUserIds.contains(member.getUser().getId())) {
                remindedMembers.add(member.getUser().getFullName());

                // Send in-app notification if notification repository exists
                try {
                    Notification notification = Notification.builder()
                            .user(member.getUser())
                            .community(cycle.getCircle().getCommunity())
                            .type(NotificationType.GENERAL)
                            .category(NotificationCategory.GENERAL)
                            .title("Kitty Contribution Reminder")
                            .body("Reminder: Your monthly contribution of ₹" + cycle.getContributionAmount() +
                                    " for " + cycle.getCycleName() + " (Period " + targetPeriod + ") is pending.")
                            .referenceType(ReferenceType.COMMUNITY)
                            .referenceId(cycle.getCircle().getCommunity().getId())
                            .actionUrl("/kitty-party/" + cycle.getCircle().getId())
                            .build();
                    notificationRepository.save(notification);
                } catch (Exception e) {
                    log.warn("Failed to create in-app notification for user {}: {}", member.getUser().getId(), e.getMessage());
                }

                // Dispatch via UnifiedNotificationService (Push, WhatsApp, SMS per resident preferences)
                if (unifiedNotificationService != null) {
                    try {
                        unifiedNotificationService.orchestrate(
                                NotificationDtos.UnifiedNotificationRequest.builder()
                                        .recipientUserId(member.getUser().getId())
                                        .category(NotificationEnums.NotificationCategory.FINANCIAL_BILLING)
                                        .priority(NotificationEnums.NotificationPriority.HIGH)
                                        .title("👛 Kitty Contribution Reminder")
                                        .body("Reminder: Your monthly contribution of ₹" + cycle.getContributionAmount() +
                                                " for " + cycle.getCycleName() + " (Period " + targetPeriod + ") is pending.")
                                        .actionUrl("/kitty-party/" + cycle.getCircle().getId())
                                        .build()
                        );
                    } catch (Exception e) {
                        log.debug("Unified notification dispatch skipped for user {}: {}", member.getUser().getId(), e.getMessage());
                    }
                }
            }
        }

        // Feature 8: Record Reminders in Audit Log
        recordAuditLog(
                cycle,
                cycle.getCircle(),
                "PAYMENT_REMINDERS_SENT",
                adminUser,
                "Payment reminders dispatched for Period " + targetPeriod + " to " + remindedMembers.size() + " members",
                "{\"periodNumber\":" + targetPeriod + ",\"remindedCount\":" + remindedMembers.size() + "}"
        );

        return SendRemindersResponse.builder()
                .periodNumber(targetPeriod)
                .remindedCount(remindedMembers.size())
                .remindedMembers(remindedMembers)
                .message("Dispatched payment reminders to " + remindedMembers.size() + " members.")
                .build();
    }

