    @Transactional
    public CycleSummaryResponse adminSwapRotation(Long cycleId, AppUser adminUser, SwapRotationRequest request) {
        KittyPartyCycle cycle = cycleRepository.findById(cycleId)
                .orElseThrow(() -> new IllegalArgumentException("Cycle not found"));

        authorizationService.assertAdminOrOwner(cycle.getCircle().getId(), adminUser.getId());

        if (request.getFromPeriod().equals(request.getToPeriod())) {
            throw new IllegalArgumentException("Cannot swap the same period with itself");
        }

        KittyPartyRotation rotFrom = rotationRepository.findByCycleIdAndPeriodNumber(cycleId, request.getFromPeriod())
                .orElseThrow(() -> new IllegalArgumentException("Rotation not found for period " + request.getFromPeriod()));

        KittyPartyRotation rotTo = rotationRepository.findByCycleIdAndPeriodNumber(cycleId, request.getToPeriod())
                .orElseThrow(() -> new IllegalArgumentException("Rotation not found for period " + request.getToPeriod()));

        if ("DISBURSED".equalsIgnoreCase(rotFrom.getRotationStatus()) || "DISBURSED".equalsIgnoreCase(rotTo.getRotationStatus())) {
            throw new IllegalStateException("Cannot swap periods that have already been disbursed");
        }

        // Safe period swap using negative temporary period to prevent unique constraint collision
        int tempNegativePeriod = -request.getFromPeriod() - 1000;
        rotFrom.setPeriodNumber(tempNegativePeriod);
        rotationRepository.saveAndFlush(rotFrom);

        rotTo.setPeriodNumber(request.getFromPeriod());
        rotTo.setRotationStatus("SWAPPED");
        rotationRepository.saveAndFlush(rotTo);

        rotFrom.setPeriodNumber(request.getToPeriod());
        rotFrom.setRotationStatus("SWAPPED");
        rotationRepository.saveAndFlush(rotFrom);

        // Feature 8: Record Swap in Audit Log
        recordAuditLog(
                cycle,
                cycle.getCircle(),
                "ROTATION_SWAPPED",
                adminUser,
                "Admin swapped rotation between Period " + request.getFromPeriod() + " (" + rotTo.getBeneficiaryUser().getFullName() + ") and Period " + request.getToPeriod() + " (" + rotFrom.getBeneficiaryUser().getFullName() + "). Reason: " + request.getReason(),
                "{\"fromPeriod\":" + request.getFromPeriod() + ",\"toPeriod\":" + request.getToPeriod() + ",\"reason\":\"" + request.getReason() + "\"}"
        );

        log.info("Admin {} swapped periods {} and {} for cycle {}", adminUser.getId(), request.getFromPeriod(), request.getToPeriod(), cycleId);
        return getCycleSummary(cycleId);
    }

