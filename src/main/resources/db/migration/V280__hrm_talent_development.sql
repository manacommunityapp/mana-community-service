-- V280: HRM Talent & Employee Development Module
-- Recruitment Pipeline
CREATE TABLE hr_job_postings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    department VARCHAR(255),
    location VARCHAR(255),
    description TEXT,
    requirements TEXT,
    employment_type VARCHAR(50),
    min_salary DECIMAL(15,2),
    max_salary DECIMAL(15,2),
    currency VARCHAR(10),
    openings INT DEFAULT 1,
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    posted_date DATE,
    closing_date DATE,
    created_by BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hr_applicants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    job_posting_id BIGINT NOT NULL REFERENCES hr_job_postings(id),
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    phone VARCHAR(50),
    resume_url VARCHAR(500),
    cover_letter TEXT,
    status VARCHAR(50) NOT NULL DEFAULT 'APPLIED',
    source VARCHAR(100),
    notes TEXT,
    applied_date DATE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hr_interviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    applicant_id BIGINT NOT NULL REFERENCES hr_applicants(id),
    interviewer_employee_id BIGINT REFERENCES hr_employees(id),
    interview_type VARCHAR(100),
    scheduled_at TIMESTAMP,
    duration_minutes INT,
    location_or_link VARCHAR(500),
    outcome VARCHAR(50),
    rating INT,
    feedback TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hr_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    applicant_id BIGINT NOT NULL REFERENCES hr_applicants(id),
    offered_salary DECIMAL(15,2),
    currency VARCHAR(10),
    joining_date DATE,
    offer_expiry_date DATE,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    notes TEXT,
    created_by BIGINT,
    responded_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Performance Management
CREATE TABLE hr_appraisal_cycles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    appraisal_window_start DATE,
    appraisal_window_end DATE,
    status VARCHAR(50) NOT NULL DEFAULT 'DRAFT',
    description TEXT,
    created_by BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hr_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL REFERENCES hr_employees(id),
    appraisal_cycle_id BIGINT REFERENCES hr_appraisal_cycles(id),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    is_kra BOOLEAN DEFAULT FALSE,
    weightage DECIMAL(5,2),
    target_value VARCHAR(255),
    current_value VARCHAR(255),
    achievement_percent INT DEFAULT 0,
    due_date DATE,
    status VARCHAR(50) DEFAULT 'IN_PROGRESS',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hr_appraisal_forms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL REFERENCES hr_employees(id),
    appraisal_cycle_id BIGINT NOT NULL REFERENCES hr_appraisal_cycles(id),
    reviewer_id BIGINT REFERENCES hr_employees(id),
    self_rating INT,
    self_comments TEXT,
    manager_rating INT,
    manager_comments TEXT,
    final_rating INT,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING_SELF',
    submitted_at TIMESTAMP,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (employee_id, appraisal_cycle_id)
);

-- OKRs
CREATE TABLE hr_okrs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    employee_id BIGINT REFERENCES hr_employees(id),
    objective VARCHAR(500) NOT NULL,
    quarter VARCHAR(10),
    year INT,
    overall_progress INT DEFAULT 0,
    status VARCHAR(50) DEFAULT 'ACTIVE',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hr_okr_key_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    okr_id BIGINT NOT NULL REFERENCES hr_okrs(id),
    title VARCHAR(500) NOT NULL,
    target_value VARCHAR(255),
    current_value VARCHAR(255),
    progress_percent INT DEFAULT 0,
    unit VARCHAR(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 360 Feedback
CREATE TABLE hr_feedback_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    subject_employee_id BIGINT NOT NULL REFERENCES hr_employees(id),
    appraisal_cycle_id BIGINT REFERENCES hr_appraisal_cycles(id),
    deadline DATE,
    is_anonymous BOOLEAN DEFAULT TRUE,
    status VARCHAR(50) DEFAULT 'OPEN',
    created_by BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hr_feedback_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feedback_request_id BIGINT NOT NULL REFERENCES hr_feedback_requests(id),
    reviewer_id BIGINT NOT NULL REFERENCES hr_employees(id),
    overall_rating INT,
    communication_rating INT,
    teamwork_rating INT,
    technical_rating INT,
    leadership_rating INT,
    strengths TEXT,
    improvements TEXT,
    additional_comments TEXT,
    submitted_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (feedback_request_id, reviewer_id)
);

-- Learning & Development
CREATE TABLE hr_training_programs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    training_type VARCHAR(100),
    provider VARCHAR(255),
    duration_hours INT,
    is_mandatory BOOLEAN DEFAULT FALSE,
    max_participants INT,
    start_date DATE,
    end_date DATE,
    status VARCHAR(50) DEFAULT 'UPCOMING',
    tags VARCHAR(500),
    created_by BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE hr_training_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL REFERENCES hr_employees(id),
    training_program_id BIGINT NOT NULL REFERENCES hr_training_programs(id),
    enrolled_date DATE NOT NULL,
    completion_date DATE,
    status VARCHAR(50) DEFAULT 'ENROLLED',
    score INT,
    feedback TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (employee_id, training_program_id)
);

-- Certifications
CREATE TABLE hr_certifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL REFERENCES hr_employees(id),
    certification_name VARCHAR(255) NOT NULL,
    issuing_organization VARCHAR(255),
    credential_id VARCHAR(255),
    issued_date DATE,
    expiry_date DATE,
    certificate_url VARCHAR(500),
    reminder_sent BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Career Paths
CREATE TABLE hr_career_paths (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL REFERENCES hr_employees(id),
    current_role VARCHAR(255),
    target_role VARCHAR(255) NOT NULL,
    target_timeline_months INT,
    mentor_employee_id BIGINT REFERENCES hr_employees(id),
    milestones TEXT,
    skills_to_develop TEXT,
    status VARCHAR(50) DEFAULT 'ACTIVE',
    notes TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Recognition
CREATE TABLE hr_recognitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    giver_employee_id BIGINT NOT NULL REFERENCES hr_employees(id),
    receiver_employee_id BIGINT NOT NULL REFERENCES hr_employees(id),
    recognition_type VARCHAR(50) NOT NULL DEFAULT 'KUDOS',
    category VARCHAR(100),
    message TEXT NOT NULL,
    points INT DEFAULT 0,
    is_public BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Indexes for performance
CREATE INDEX idx_hr_job_postings_org ON hr_job_postings(organization_id);
CREATE INDEX idx_hr_job_postings_status ON hr_job_postings(organization_id, status);
CREATE INDEX idx_hr_applicants_org ON hr_applicants(organization_id);
CREATE INDEX idx_hr_applicants_posting ON hr_applicants(job_posting_id);
CREATE INDEX idx_hr_interviews_applicant ON hr_interviews(applicant_id);
CREATE INDEX idx_hr_interviews_interviewer ON hr_interviews(organization_id, interviewer_employee_id);
CREATE INDEX idx_hr_offers_applicant ON hr_offers(applicant_id);
CREATE INDEX idx_hr_appraisal_cycles_org ON hr_appraisal_cycles(organization_id);
CREATE INDEX idx_hr_goals_employee ON hr_goals(employee_id);
CREATE INDEX idx_hr_goals_cycle ON hr_goals(employee_id, appraisal_cycle_id);
CREATE INDEX idx_hr_appraisal_forms_employee ON hr_appraisal_forms(employee_id);
CREATE INDEX idx_hr_okrs_org ON hr_okrs(organization_id);
CREATE INDEX idx_hr_okrs_employee ON hr_okrs(employee_id);
CREATE INDEX idx_hr_okr_key_results_okr ON hr_okr_key_results(okr_id);
CREATE INDEX idx_hr_feedback_requests_subject ON hr_feedback_requests(subject_employee_id);
CREATE INDEX idx_hr_feedback_responses_request ON hr_feedback_responses(feedback_request_id);
CREATE INDEX idx_hr_training_programs_org ON hr_training_programs(organization_id);
CREATE INDEX idx_hr_training_enrollments_employee ON hr_training_enrollments(employee_id);
CREATE INDEX idx_hr_certifications_employee ON hr_certifications(employee_id);
CREATE INDEX idx_hr_certifications_expiry ON hr_certifications(organization_id, expiry_date, reminder_sent);
CREATE INDEX idx_hr_career_paths_employee ON hr_career_paths(employee_id);
CREATE INDEX idx_hr_recognitions_org_public ON hr_recognitions(organization_id, is_public);
CREATE INDEX idx_hr_recognitions_receiver ON hr_recognitions(receiver_employee_id);
